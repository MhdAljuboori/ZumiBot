import { defineConfig } from 'astro/config'
import starlight from '@astrojs/starlight'
import starlightLinksValidator from 'starlight-links-validator'
import { SIDEBAR } from './src/sidebar.ts'
import { inlineHashes } from './src/lib/cspIntegration.ts'

// No `editLink`: pages never send readers into the source. `social` holds only the repo's home page and the contact address.
export default defineConfig({
  site: 'https://docs.zumibot.run',
  security: {
    // Each page gets a CSP meta with hashes of its own scripts and styles. `vercel.json` sends a looser header CSP
    // ('unsafe-inline') because Starlight's inline theme and search scripts need it there. That is safe: a page is held
    // to both policies, so the meta's hashes are what actually apply, and `scripts/checkDist.mjs` fails the build when
    // a page has no meta. 'wasm-unsafe-eval' is for Pagefind, which runs WebAssembly. Astro leaves Starlight's inline
    // scripts and style attributes unhashed, so `inlineHashes()` adds their hashes to the meta after the build.
    csp: { scriptDirective: { resources: ["'self'", "'wasm-unsafe-eval'"] } }
  },
  integrations: [
    inlineHashes(),
    starlight({
      title: 'ZumiBot',
      // A broken internal link fails `astro build`.
      plugins: [starlightLinksValidator()],
      logo: { src: './src/assets/zumi-z.svg' },
      social: [
        { icon: 'github', label: 'GitHub', href: 'https://github.com/MhdAljuboori/ZumiBot' },
        { icon: 'email', label: 'Email contact@zumibot.run', href: 'mailto:contact@zumibot.run' }
      ],
      favicon: '/favicon.png',
      customCss: ['@fontsource-variable/bricolage-grotesque', './src/styles/brand.css'],
      // Since Starlight 0.39 an autogenerated folder sits inside a labeled group's `items`.
      sidebar: SIDEBAR.map(({ label, directory }) => ({ label, items: [{ autogenerate: { directory } }] }))
    })
  ]
})
